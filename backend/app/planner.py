"""Turn introspected MySQL metadata into an ordered PostgreSQL migration plan."""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field

from .introspect import DatabaseInfo, Table
from .models import MigrationOptions
from .typemap import BINARY_TYPES, MappedColumn, map_column, mq, ql, qi

PG_MAX_IDENT = 63
FK_RULES = {"CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT", "NO ACTION"}


@dataclass
class Step:
    label: str
    sql: str
    fallback_sql: str | None = None  # tried if ``sql`` fails


@dataclass
class TablePlan:
    database: str
    source_table: str
    schema: str
    name: str
    row_estimate: int
    column_names: list[str]
    select_sql: str
    converters: list
    create_sql: str
    post_steps: list[Step] = field(default_factory=list)

    @property
    def key(self) -> str:
        return f"{self.database}.{self.source_table}"

    @property
    def qualified(self) -> str:
        return f"{qi(self.schema)}.{qi(self.name)}"


@dataclass
class Plan:
    schema_steps: list[Step] = field(default_factory=list)
    tables: list[TablePlan] = field(default_factory=list)
    fk_steps: list[Step] = field(default_factory=list)
    view_steps: list[Step] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_sql(self) -> str:
        out: list[str] = ["-- Generated by mysql2pgs", "SET TIME ZONE 'UTC';", ""]

        def emit(title: str, steps: list[Step]):
            if steps:
                out.append(f"-- ===== {title} =====")
                for s in steps:
                    out.append(f"-- {s.label}")
                    out.append(s.sql.rstrip(";") + ";")
                out.append("")

        emit("Schemas", self.schema_steps)
        emit("Tables", [Step(f"table {t.key}", t.create_sql) for t in self.tables])
        out.append("-- (data is copied here with COPY ... FROM STDIN)")
        out.append("")
        emit("Keys, indexes, sequences, triggers, comments", [s for t in self.tables for s in t.post_steps])
        emit("Foreign keys", self.fk_steps)
        emit("Views", self.view_steps)
        if self.warnings:
            out.append("-- ===== Warnings =====")
            out.extend(f"-- {w}" for w in self.warnings)
        return "\n".join(out)


def pg_ident(name: str, opts: MigrationOptions) -> str:
    return name.lower() if opts.lowercase_identifiers else name


def short_name(*parts: str) -> str:
    """Join parts into an identifier, hashing the tail if it exceeds 63 bytes."""
    name = "_".join(p for p in parts if p)
    if len(name.encode()) <= PG_MAX_IDENT:
        return name
    digest = hashlib.md5(name.encode()).hexdigest()[:8]
    return name.encode()[: PG_MAX_IDENT - 9].decode(errors="ignore") + "_" + digest


def translate_view_sql(definition: str, schema_map: dict[str, str], opts: MigrationOptions) -> str:
    """Best-effort rewrite of a MySQL view body into PostgreSQL syntax."""

    def repl(m: re.Match) -> str:
        ident = m.group(1).replace("``", "`")
        if ident in schema_map:
            return qi(schema_map[ident])
        return qi(pg_ident(ident, opts))

    sql = re.sub(r"`((?:[^`]|``)+)`", repl, definition)
    sql = re.sub(r"\bifnull\s*\(", "coalesce(", sql, flags=re.I)
    sql = re.sub(r"\bnow\s*\(\s*\)", "now()", sql, flags=re.I)
    sql = re.sub(r"\bcurdate\s*\(\s*\)", "current_date", sql, flags=re.I)
    # MySQL emits `_utf8mb4'literal'` / `_latin1'literal'` charset introducers.
    sql = re.sub(r"\b_(utf8mb4|utf8|latin1|binary|ascii)'", "'", sql, flags=re.I)
    return sql


def _column_list(names: list[str]) -> str:
    return ", ".join(qi(n) for n in names)


def build_table(db: DatabaseInfo, table: Table, schema: str, opts: MigrationOptions, warnings: list[str]) -> TablePlan:
    tname = pg_ident(table.name, opts)
    qualified = f"{qi(schema)}.{qi(tname)}"
    col_defs: list[str] = []
    select_exprs: list[str] = []
    converters: list = []
    target_cols: list[str] = []
    post: list[Step] = []
    mapped: dict[str, MappedColumn] = {}

    for col in table.columns:
        cname = pg_ident(col.name, opts)
        m = map_column(col, cname, opts.tinyint1_as_boolean)
        mapped[col.name] = m
        warnings.extend(f"{db.name}.{table.name}: {w}" for w in m.warnings)
        parts = [qi(cname), m.pg_type]
        if m.identity:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if m.default_sql is not None:
            parts.append(f"DEFAULT {m.default_sql}")
        if not col.nullable:
            parts.append("NOT NULL")
        if m.check_sql:
            parts.append(m.check_sql)
        col_defs.append(" ".join(parts))
        select_exprs.append(m.select_expr)
        converters.append(m.converter)
        target_cols.append(cname)

        if m.identity:
            post.append(Step(
                f"sync identity {tname}.{cname}",
                f"SELECT setval(pg_get_serial_sequence({ql(qualified)}, {ql(cname)}), "
                f"COALESCE(MAX({qi(cname)}), 0) + 1, false) FROM {qualified}",
            ))
        if m.on_update_current_timestamp:
            fn = f"{qi(schema)}.{qi(short_name('trg', tname, cname, 'on_update'))}"
            post.append(Step(
                f"ON UPDATE CURRENT_TIMESTAMP trigger {tname}.{cname}",
                f"CREATE OR REPLACE FUNCTION {fn}() RETURNS trigger LANGUAGE plpgsql AS $fn$\n"
                f"BEGIN\n  NEW.{qi(cname)} := CURRENT_TIMESTAMP;\n  RETURN NEW;\nEND\n$fn$;\n"
                f"CREATE TRIGGER {qi(short_name(tname, cname, 'on_update'))} BEFORE UPDATE ON {qualified} "
                f"FOR EACH ROW EXECUTE FUNCTION {fn}()",
            ))
        if col.comment:
            post.append(Step(f"comment {tname}.{cname}", f"COMMENT ON COLUMN {qualified}.{qi(cname)} IS {ql(col.comment)}"))

    if table.comment:
        post.insert(0, Step(f"comment {tname}", f"COMMENT ON TABLE {qualified} IS {ql(table.comment)}"))

    # Primary key and indexes are built after the data load: far faster than
    # maintaining them during COPY.
    index_steps: list[Step] = []
    for idx in table.indexes:
        cols = [pg_ident(c, opts) for c, _ in idx.columns]
        if idx.name == "PRIMARY":
            index_steps.insert(0, Step(
                f"primary key {tname}",
                f"ALTER TABLE {qualified} ADD CONSTRAINT {qi(short_name(tname, 'pkey'))} PRIMARY KEY ({_column_list(cols)})",
            ))
            continue
        if not opts.create_indexes:
            continue
        iname = qi(short_name(tname, pg_ident(idx.name, opts)))
        if idx.index_type == "FULLTEXT":
            doc = " || ' ' || ".join(f"coalesce({qi(c)}, '')" for c in cols)
            index_steps.append(Step(
                f"fulltext index {tname}.{idx.name} (as GIN tsvector)",
                f"CREATE INDEX {iname} ON {qualified} USING gin (to_tsvector('simple', {doc}))",
            ))
            continue
        if idx.index_type == "SPATIAL":
            warnings.append(f"{db.name}.{table.name}: spatial index {idx.name} skipped (columns stored as WKT text)")
            continue

        # Prefix indexes (e.g. KEY (title(50))) become expression indexes.
        exprs: list[str] = []
        has_prefix = False
        for (src_col, sub), cname in zip(idx.columns, cols):
            if sub is None:
                exprs.append(qi(cname))
                continue
            has_prefix = True
            src = next((c for c in table.columns if c.name == src_col), None)
            if src is not None and src.data_type in BINARY_TYPES:
                exprs.append(f"(substring({qi(cname)} from 1 for {sub}))")
            else:
                exprs.append(f"(left({qi(cname)}, {sub}))")
        unique = "UNIQUE " if idx.unique else ""
        create = f"CREATE {unique}INDEX {iname} ON {qualified} ({', '.join(exprs)})"
        if has_prefix and not idx.unique:
            # A full-column index serves equality lookups better; fall back to the
            # prefix expression if the values are too large for a btree entry.
            index_steps.append(Step(
                f"index {tname}.{idx.name}",
                f"CREATE INDEX {iname} ON {qualified} ({_column_list(cols)})",
                fallback_sql=create,
            ))
        else:
            index_steps.append(Step(f"{'unique ' if idx.unique else ''}index {tname}.{idx.name}", create))

    create_sql = f"CREATE TABLE {qualified} (\n  " + ",\n  ".join(col_defs) + "\n)"
    select_sql = f"SELECT {', '.join(select_exprs)} FROM {mq(db.name)}.{mq(table.name)}"
    return TablePlan(
        database=db.name,
        source_table=table.name,
        schema=schema,
        name=tname,
        row_estimate=table.row_estimate,
        column_names=target_cols,
        select_sql=select_sql,
        converters=converters,
        create_sql=create_sql,
        post_steps=index_steps + post,
    )


def build_plan(databases: list[tuple[DatabaseInfo, str]], opts: MigrationOptions) -> Plan:
    """``databases`` is a list of (introspected database, target schema)."""
    plan = Plan()
    schema_map = {db.name: schema for db, schema in databases}
    migrated_tables = {(db.name, t.name) for db, _ in databases for t in db.tables}

    for db, schema in databases:
        if opts.drop_existing:
            plan.schema_steps.append(Step(f"drop schema {schema}", f"DROP SCHEMA IF EXISTS {qi(schema)} CASCADE"))
        plan.schema_steps.append(Step(f"create schema {schema}", f"CREATE SCHEMA IF NOT EXISTS {qi(schema)}"))
        if db.routine_count:
            plan.warnings.append(f"{db.name}: {db.routine_count} stored routine(s) not migrated (manual port required)")
        if db.trigger_count:
            plan.warnings.append(f"{db.name}: {db.trigger_count} trigger(s) not migrated (manual port required)")

        for table in db.tables:
            if not table.columns:
                continue
            plan.tables.append(build_table(db, table, schema, opts, plan.warnings))

            if not opts.create_foreign_keys:
                continue
            tname = pg_ident(table.name, opts)
            for fk in table.foreign_keys:
                if (fk.ref_schema, fk.ref_table) not in migrated_tables:
                    plan.warnings.append(
                        f"{db.name}.{table.name}: foreign key {fk.name} skipped "
                        f"(references {fk.ref_schema}.{fk.ref_table}, which is not being migrated)"
                    )
                    continue
                ref = f"{qi(schema_map[fk.ref_schema])}.{qi(pg_ident(fk.ref_table, opts))}"
                on_update = fk.on_update if fk.on_update in FK_RULES else "NO ACTION"
                on_delete = fk.on_delete if fk.on_delete in FK_RULES else "NO ACTION"
                plan.fk_steps.append(Step(
                    f"foreign key {tname}.{fk.name}",
                    f"ALTER TABLE {qi(schema)}.{qi(tname)} ADD CONSTRAINT {qi(short_name(pg_ident(fk.name, opts)))} "
                    f"FOREIGN KEY ({_column_list([pg_ident(c, opts) for c in fk.columns])}) "
                    f"REFERENCES {ref} ({_column_list([pg_ident(c, opts) for c in fk.ref_columns])}) "
                    f"ON UPDATE {on_update} ON DELETE {on_delete}",
                ))

        if opts.create_views:
            for view in db.views:
                body = translate_view_sql(view.definition, schema_map, opts)
                plan.view_steps.append(Step(
                    f"view {schema}.{pg_ident(view.name, opts)}",
                    f"CREATE OR REPLACE VIEW {qi(schema)}.{qi(pg_ident(view.name, opts))} AS {body}",
                ))
    return plan
